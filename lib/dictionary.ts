export function getDictionary(locale: Locale): typeof EN_DICT {
  return (locale === "ar" ? AR_DICT : EN_DICT) as typeof EN_DICT;
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const dict = getDictionary(locale);
  let s: string = String(dict[key] ?? EN_DICT[key] ?? key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}
